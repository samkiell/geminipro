import { readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { asc, eq, sql } from 'drizzle-orm';
import type { AlbumPhoto, Keyboard, TelegramPort } from '../bot/telegram.js';
import { cb, supportButton, type UiFacts } from '../bot/views.js';
import { PROOF_AFTER, PROOF_CAPTION, PROOF_INTRO, PROOF_MISSING } from '../content/replies.js';
import type { Db } from '../db/client.js';
import { proofItems } from '../db/schema.js';
import type { Logger } from '../util/logger.js';
import type { Notify } from './notifier.js';

// Real proof for skeptical buyers (Prompt C section 6): screenshots of real activations, details
// blurred, sent as one album. The first send uploads from assets/proof/; Telegram's file_id is
// kept so every later send is instant. Never edited or generated by the bot.

export const MAX_PROOF = 10;
const IMAGE = /\.(jpe?g|png)$/i;

export interface ProofDeps {
  db: Db;
  port: TelegramPort;
  facts: UiFacts;
  notify: Notify;
  logger: Logger;
  /** assets/proof */
  dir: string;
}

export type ProofItem = typeof proofItems.$inferSelect;

/** Active items in album order, at most 10. */
export function activeProof(db: Db): Promise<ProofItem[]> {
  return db.select().from(proofItems).where(eq(proofItems.active, true)).orderBy(asc(proofItems.position), asc(proofItems.id)).limit(MAX_PROOF);
}

/** At boot: when the table is empty, one row per image in the folder (by file name). */
export async function seedProof(db: Db, dir: string): Promise<number> {
  const [{ n } = { n: 0 }] = await db.select({ n: sql<number>`count(*)::int` }).from(proofItems);
  if (n > 0) return 0;
  let files: string[];
  try {
    files = (await readdir(dir)).filter((f) => IMAGE.test(f)).sort();
  } catch {
    return 0;
  }
  if (files.length === 0) return 0;
  await db
    .insert(proofItems)
    .values(files.slice(0, MAX_PROOF).map((key, position) => ({ key, position })))
    .onConflictDoNothing();
  return Math.min(files.length, MAX_PROOF);
}

/** An admin's photo: stored by its Telegram file_id, last in the album. */
export async function addProof(db: Db, fileId: string, fileUniqueId: string): Promise<'added' | 'exists' | 'full'> {
  if ((await activeProof(db)).length >= MAX_PROOF) return 'full';
  const [{ next } = { next: 0 }] = await db
    .select({ next: sql<number>`coalesce(max(${proofItems.position}) + 1, 0)::int` })
    .from(proofItems);
  const [row] = await db
    .insert(proofItems)
    .values({ key: `tg:${fileUniqueId}`, fileId, position: next })
    .onConflictDoNothing()
    .returning({ id: proofItems.id });
  return row ? 'added' : 'exists';
}

/** Deletes the screenshot with this id (as /proofs shows it), for good: it can be added again later. */
export async function removeProof(db: Db, id: number): Promise<ProofItem | undefined> {
  const [item] = await db.delete(proofItems).where(eq(proofItems.id, id)).returning();
  return item;
}

export function createProof(deps: ProofDeps) {
  const { db, port } = deps;
  const after: Keyboard = [[{ text: 'buy now', data: cb.buy(1) }, supportButton(deps.facts, undefined, 'whatsapp support')]];

  /** The fixed text, the album, then what to do next. */
  async function send(telegramId: number): Promise<'sent' | 'missing'> {
    const items = await activeProof(db);
    if (items.length === 0) {
      await port.send(telegramId, { text: PROOF_MISSING, keyboard: [[supportButton(deps.facts, undefined, 'whatsapp support')]] });
      deps.notify({
        level: 'warning',
        title: 'no proof screenshots yet',
        body: 'A buyer asked for proof and there is none to show. Add screenshots to assets/proof/ (blurred) or send one to the bot with the caption /addproof.',
        cooldownKey: 'proof_missing',
      });
      return 'missing';
    }
    await port.send(telegramId, { text: PROOF_INTRO });
    const photos: AlbumPhoto[] = items.map((i) => (i.fileId ? { fileId: i.fileId } : { path: join(deps.dir, i.key) }));
    const fileIds = await port.sendAlbum(telegramId, photos, PROOF_CAPTION);
    // Remember uploads, so the next album is sent by file_id.
    for (const [i, item] of items.entries()) {
      const fileId = fileIds[i];
      if (!item.fileId && fileId) await db.update(proofItems).set({ fileId }).where(eq(proofItems.id, item.id));
    }
    await port.send(telegramId, { text: PROOF_AFTER, keyboard: after });
    return 'sent';
  }

  return { send };
}

export type Proof = ReturnType<typeof createProof>;
